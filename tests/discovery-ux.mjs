import assert from 'node:assert/strict';
import {rankCities} from '../lib/city-search.js';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const cities=[{id:1,name:'New YorkJersey CityNewark urban area',population:20000000},{id:2,name:'New York County',population:2000000},{id:3,name:'New York City',population:8000000},{id:4,name:'New York Mills',population:3000}];
assert.equal(rankCities(cities,'New York','US')[0].id,3);
assert.equal(rankCities(cities,'NYC','US')[0].id,3);
assert.equal(rankCities(cities,'New York Mills','US')[0].id,4);
assert.equal(rankCities(cities,'No such place','US').length,0);
assert.equal(cities[0].id,1,'Ranking must not mutate source cache');
const context={window:{},document:{addEventListener(){}}};vm.createContext(context);
vm.runInContext(readFileSync('assets/document-import.js','utf8'),context);
const parse=context.window.StudioOpeningDocumentImport.parse;
const parsed=parse('Product Designer\nCompany: Example Studio\nLocation: New York, United States\nFull-time, hybrid\nWe design accessible products.\nApply at https://example.org/careers/designer');
assert.equal(parsed.mode,'hybrid');assert.equal(parsed.type,'Full-time');assert.equal(parsed.company,'Example Studio');assert.equal(parsed.url,'https://example.org/careers/designer');
const benefits=parse('Graphic Designer\nWe offer full-time employees remote working benefits.\nVisit https://example.org to learn about our company.');
assert.equal(benefits.type,'');assert.equal(benefits.mode,'');assert.equal(benefits.url,'');
assert.equal(parse('Designer\nApply at javascript:alert(1)').url,'');
console.log('City ranking, NYC alias, exact match, conservative import and explicit Apply URL passed.');
