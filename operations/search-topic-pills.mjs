import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {LOCAL_CITIES} from '../lib/local-cities.js';
import topicSearch from '../assets/search-topics.js';

const {studios}=JSON.parse(readFileSync(new URL('../studio-registry/published.json',import.meta.url),'utf8'));
const regionNames=new Intl.DisplayNames(['en'],{type:'region'});
const countryId=country=>'country-'+country.toLowerCase();
function cityId(place){
 if(place.city===regionNames.of(place.country))return countryId(place.country);
 const id=place.cityId||place.id;
 return id==='gb--england--london'?'london':'city-'+id;
}
const placeTopics=new Map();
for(const studio of studios){
 for(const office of studio.offices.filter(office=>office.kind==='office')){
  const {city,country,region}=office;
  const countryName=regionNames.of(country);
  placeTopics.set(countryId(country),{id:countryId(country),label:countryName,country});
  const id=cityId(office);
  if(id!==countryId(country))placeTopics.set(id,{id,label:city,city,cityId:office.cityId,country,region,countryName});
 }
}
const geographicTopics=[...placeTopics.values()].sort((a,b)=>a.label.localeCompare(b.label,'en'));
const search=topicSearch.create(geographicTopics);
const byId=new Map(search.topics.map(topic=>[topic.id,topic]));
const escapeHtml=value=>String(value).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');

export function renderGeographicTopics(){
 return '// Generated by operations/build-studio-index.mjs. Do not edit.\n'+
  '(function(root){var topics='+JSON.stringify(geographicTopics)+
  ';if(typeof module!=="undefined"&&module.exports)module.exports=topics;else root.SOAPPGeographicTopics=topics;})(typeof window!=="undefined"?window:globalThis);\n';
}

export function studioTopicIds(studio){
 const offices=studio.offices.filter(office=>office.kind==='office');
 const focus=search.topics.filter(topic=>topic.discipline&&search.matchesDiscipline(topic,studio.disciplines,studio.summary+' '+studio.overview)).map(topic=>topic.id);
 return [...new Set([...offices.map(cityId),...offices.map(office=>countryId(office.country)),...focus])];
}

export function articleTopicIds(article){
 const explicit=article.searchTopics??[];
 assert.ok(Array.isArray(explicit),'Article search topics must be a list');
 const offices=LOCAL_CITIES.filter(place=>(article.cityIds||[]).includes(place.id));
 const geographic=offices.flatMap(place=>[cityId(place),countryId(place.country)]).filter(id=>byId.has(id));
 return [...new Set([...geographic,...explicit])];
}

export function topicAttributes(ids=[]){
 assert.ok(Array.isArray(ids),'Search topics must be a list');
 if(!ids.length)return '';
 assert.ok(ids.every(id=>byId.has(id))&&new Set(ids).size===ids.length,'Invalid or duplicate search topic');
 return ' data-topics="'+ids.join(' ')+'"';
}

export function renderTopicPills(ids=[]){
 if(!topicAttributes(ids))return '';
 return '<nav class="so-topic-pills" aria-label="Search by topic">'+ids.map(id=>{
  const {label}=byId.get(id);
  return '<a href="/?q='+encodeURIComponent(label)+'">'+escapeHtml(label)+'</a>';
 }).join(' ')+'</nav>';
}
